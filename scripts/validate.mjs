import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import vm from 'node:vm';
import { MINT } from './snapshot.mjs';
import { staticHandler } from './static.mjs';
const root = new URL('../dist/', import.meta.url);
const handler = staticHandler(root);
const response = await handler.fetch(new Request('https://example.test/'));
assert.equal(response.status, 200);
const html = await response.text();
assert.match(html, /项目概览/);
assert.doesNotMatch(html, /fetch\(['"]\/api\//);
assert.match(html, /\.\/data\/snapshot\.json/);
assert.doesNotMatch(html, /仅自己可见|appgprj_/);
for (const [, script] of html.matchAll(/<script>([\s\S]*?)<\/script>/g)) new vm.Script(script);
const snapshot = JSON.parse(await readFile(new URL('data/snapshot.json', root), 'utf8'));
assert.equal(snapshot.mint, MINT);
assert.equal((await handler.fetch(new Request('https://example.test/data/snapshot.json'))).status, 200);
assert.equal((await handler.fetch(new Request('https://example.test/not-found'))).status, 404);
assert.equal((await handler.fetch(new Request('https://example.test/', { method: 'POST' }))).status, 405);
assert.equal(new URL('./data/snapshot.json', 'https://keithprayer.github.io/usePaid/').pathname, '/usePaid/data/snapshot.json');
console.log('Static Pages build, relative data URL, frontend syntax, snapshot mint and routes verified.');
